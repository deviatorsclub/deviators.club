/**
 * Normalizes input slugs such as:
 * - "invitation-ashima-mehta"
 * - "invite-ashima-mehta"
 * - "ashima-mehta"
 * - "prof-ashima-mehta"
 */
export function normalizeFacultySlug(rawSlug: string): string {
  if (!rawSlug) return "";
  let clean = decodeURIComponent(rawSlug).trim().toLowerCase();
  clean = clean.replace(/^(invitation|invite)[-_]/, "");
  clean = clean.replace(/^(prof|dr)[-_]/, "");
  return clean;
}

/**
 * Retrieves faculty invitation by slug.
 * Returns null if the slug is not one of the approved faculty members.
 */
export function getFacultyInvitation(
  rawSlug: string,
): FacultyInvitation | null {
  const normalized = normalizeFacultySlug(rawSlug);
  return FACULTY_INVITATIONS[normalized] || null;
}
